#!/usr/bin/env python3
"""bdf2font.py - ASCII glyphs of a BDF bitmap font as a C table for the
translator's panel console (dbt/rt/lcdcon.c).

  bdf2font.py <font.bdf> <out.h> [cell_w cell_h]

Takes the 95 printable ASCII glyphs (32..126), places each in a cell_w x
cell_h cell (default 4x8: ~/Dev/FontChinese7x7/JiZhi-bitmap-8.bdf, MIT, a
4-pixel half-width font with ascent 7) and writes one byte per row, MSB =
leftmost pixel. A glyph the font lacks is blank.
"""
import sys

def parse(path):
    glyphs = {}
    ascent = 7
    with open(path, encoding='utf-8', errors='replace') as f:
        enc = None; bbx = None; rows = None
        for line in f:
            w = line.split()
            if not w: continue
            if w[0] == 'FONTBOUNDINGBOX':
                ascent = int(w[2]) + int(w[4])        # height + yoff (yoff negative = descent)
            elif w[0] == 'ENCODING':
                enc = int(w[1])
            elif w[0] == 'BBX':
                bbx = tuple(int(x) for x in w[1:5])
            elif w[0] == 'BITMAP':
                rows = []
            elif w[0] == 'ENDCHAR':
                if enc is not None and bbx is not None and rows is not None:
                    glyphs[enc] = (bbx, rows)
                enc = bbx = rows = None
            elif rows is not None:
                rows.append(int(w[0], 16))
    return ascent, glyphs

def cell(glyph, ascent, cw, ch):
    out = [0] * ch
    if glyph is None: return out
    (bw, bh, xoff, yoff), rows = glyph
    top = ascent - (yoff + bh)
    for r, bits in enumerate(rows):
        y = top + r
        if 0 <= y < ch:
            # bits: MSB = leftmost of the bbx; shift into the cell at xoff
            width_bytes = (bw + 7) // 8
            v = bits >> (width_bytes * 8 - bw)      # right-align the bw pixels
            v = (v << (cw - bw - xoff)) if cw - bw - xoff >= 0 else (v >> (bw + xoff - cw))
            out[y] = (v << (8 - cw)) & 0xFF
    return out

def main(argv):
    if len(argv) < 3:
        print(__doc__); return 2
    cw, ch = (int(argv[3]), int(argv[4])) if len(argv) >= 5 else (4, 8)
    ascent, glyphs = parse(argv[1])
    with open(argv[2], 'w') as o:
        o.write('/* generated by tools/bdf2font.py from %s: ASCII 32..126, %dx%d cells, MSB = left */\n' % (argv[1].split('/')[-1], cw, ch))
        o.write('#define LCDFONT_W %d\n#define LCDFONT_H %d\n' % (cw, ch))
        o.write('static const unsigned char lcdfont[95][%d] = {\n' % ch)
        for c in range(32, 127):
            rows = cell(glyphs.get(c), ascent, cw, ch)
            o.write('    { %s }, /* %s */\n' % (', '.join('0x%02X' % r for r in rows), chr(c) if c != 92 else 'backslash'))
        o.write('};\n')
    missing = [c for c in range(32, 127) if c not in glyphs]
    print('wrote %s, ascent %d, missing %s' % (argv[2], ascent, missing))
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv))
