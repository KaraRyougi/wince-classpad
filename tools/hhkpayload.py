#!/usr/bin/env python3
"""hhkpayload.py - describe the translator image embedded in wince.hh3.

  hhkpayload.py <dbt-image.bin>   -> C defines on stdout (PAYLOAD_SIZE, PAYLOAD_SUM)

The launcher (dbt/hhk/launcher.c) recomputes the 32-bit byte sum over the
payload after HollyHock has copied it to IMAGE_BASE and refuses to boot a
copy that does not match (a truncated transfer to the calculator).
"""
import sys

def main(argv):
    if len(argv) != 2:
        print(__doc__); return 2
    data = open(argv[1], "rb").read()
    print("/* generated by tools/hhkpayload.py from %s */" % argv[1])
    print("#define PAYLOAD_SIZE %uu" % len(data))
    print("#define PAYLOAD_SUM 0x%08xu" % (sum(data) & 0xFFFFFFFF))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
