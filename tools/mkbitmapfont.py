#!/usr/bin/env python3
"""mkbitmapfont.py - 1-bit bitmap fonts for the loader (wince.hh3) and its mockup.

    mkbitmapfont.py js          > tables for docs/design/loader-luna.html (const BMF)
    mkbitmapfont.py c <out.c>   the loader's fonts as C (dbt/hhk/font_data.c)

Rasterises hinted TrueType fonts the way Windows 2000/XP draws them without
ClearType: FreeType's mono target, full bytecode hinting, 1 bit per pixel.
Tahoma and Trebuchet MS come from macOS (/System/Library/Fonts/Supplemental).
Needs freetype-py.

C layout (hhk/gfx.h): per font a glyph table for codes FIRST..FIRST+COUNT-1,
each glyph (advance, left, top, width, height, bit offset) with its rows packed
MSB first and back to back in one bit array. Codes 0x7F.. hold the few
non-ASCII glyphs the loader prints (EXTRA); Tahoma has no arrows, so the
two triangles are drawn here.
"""
import freetype, json, sys

F = '/System/Library/Fonts/Supplemental/'
FACES = {('tahoma', 0): F + 'Tahoma.ttf', ('tahoma', 1): F + 'Tahoma Bold.ttf',
         ('trebuchet', 0): F + 'Trebuchet MS.ttf', ('trebuchet', 1): F + 'Trebuchet MS Bold.ttf'}
FLAGS = freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO | freetype.FT_LOAD_MONOCHROME

# the loader's fonts: C name -> (family, bold, pixel size)
C_FONTS = {
    'font_t9b':   ('tahoma', 1, 9),     # tags (Persistent, ...)
    'font_t10':   ('tahoma', 0, 10),    # time left
    'font_t11':   ('tahoma', 0, 11),    # body text (Tahoma 8 pt)
    'font_t11b':  ('tahoma', 1, 11),
    'font_t12b':  ('tahoma', 1, 12),    # headings, action titles
    'font_tr13b': ('trebuchet', 1, 13), # title bar (Trebuchet MS 10 pt bold)
}
FIRST = 32
EXTRA = ['·', '▲', '▼', '…']   # 0x7F, 0x80, 0x81, 0x82
ARROWS = {'▲': [0x08, 0x1c, 0x3e, 0x7f], '▼': [0x7f, 0x3e, 0x1c, 0x08]}   # 7 px wide

def glyph(face, ch, px):
    """(advance, left, top, width, height, rows as ints MSB = leftmost)"""
    if ch in ARROWS:
        return (9, 1, round(face.size.ascender / 64 * 0.62), 7, 4, ARROWS[ch])
    if face.get_char_index(ch) == 0:
        return None
    face.load_char(ch, FLAGS)
    s = face.glyph
    bm = s.bitmap
    rows = []
    for r in range(bm.rows):
        bits = 0
        for c in range(bm.width):
            if bm.buffer[r * bm.pitch + (c >> 3)] & (0x80 >> (c & 7)):
                bits |= 1 << (bm.width - 1 - c)
        rows.append(bits)
    return (s.advance.x >> 6, s.bitmap_left, s.bitmap_top, bm.width, bm.rows, rows)

def face_at(fam, bold, px):
    f = freetype.Face(FACES[(fam, bold)])
    f.set_pixel_sizes(0, px)
    return f

def js():
    sizes = {('tahoma', 0): range(6, 16), ('tahoma', 1): range(6, 16),
             ('trebuchet', 0): [10, 13, 21, 26], ('trebuchet', 1): [10, 13, 28]}
    chars = [chr(c) for c in range(32, 127)] + list('®·×…•')
    out = {}
    for (fam, b) in FACES:
        for px in sizes[(fam, b)]:
            face = face_at(fam, b, px)
            gl = {}
            for ch in chars:
                g = glyph(face, ch, px)
                if g:
                    adv, l, t, w, h, rows = g
                    gl[ch] = [adv, l, t, w, ','.join(format(r, 'x') for r in rows)]
            out[f'{fam}|{b}|{px}'] = {'asc': face.size.ascender >> 6, 'g': gl}
    sys.stdout.write('const BMF=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')

def c(path):
    o = ['/* font_data.c - generated by tools/mkbitmapfont.py c: hinted 1-bit Tahoma and',
         ' * Trebuchet MS, rows packed MSB first (hhk/gfx.h). Do not edit. */',
         '#include "gfx.h"', '']
    chars = [chr(i) for i in range(FIRST, 127)] + EXTRA
    for name, (fam, b, px) in C_FONTS.items():
        face = face_at(fam, b, px)
        bits, entries = [], []
        for ch in chars:
            g = glyph(face, ch, px) or glyph(face, '?', px)
            adv, l, t, w, h, rows = g
            entries.append((adv, l, t, w, h, len(bits)))
            for r in rows:
                bits += [(r >> (w - 1 - i)) & 1 for i in range(w)]
        data = bytearray((len(bits) + 7) // 8)
        for i, v in enumerate(bits):
            if v:
                data[i >> 3] |= 0x80 >> (i & 7)
        o.append(f'static const u8 {name}_bits[{len(data)}] = {{')
        for i in range(0, len(data), 16):
            o.append('    ' + ','.join(f'0x{v:02x}' for v in data[i:i + 16]) + ',')
        o.append('};')
        o.append(f'static const gfx_glyph {name}_glyphs[{len(entries)}] = {{')
        for e in entries:
            o.append('    {%d,%d,%d,%d,%d,%d},' % e)
        o.append('};')
        asc = face.size.ascender >> 6
        o.append(f'const gfx_font {name} = {{ {FIRST}, {len(entries)}, {asc}, {name}_glyphs, {name}_bits }};')
        o.append('')
    open(path, 'w').write('\n'.join(o))

if __name__ == '__main__':
    if len(sys.argv) >= 2 and sys.argv[1] == 'js':
        js()
    elif len(sys.argv) == 3 and sys.argv[1] == 'c':
        c(sys.argv[2])
    else:
        sys.exit(__doc__)
