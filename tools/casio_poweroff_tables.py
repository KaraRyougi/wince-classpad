#!/usr/bin/env python3
"""casio_poweroff_tables.py - generate bsp/classpad50/SRC/INC/classpad_pwrseq.h
from a dump of the calculator's NOR flash (Casio OS 02.01.7003).

    casio_poweroff_tables.py NOR.bin [-o classpad_pwrseq.h]

The tables are what the OS's own power-off and power-on routines do to the
hardware, recorded by running them in tools/sh4trace.py:
  - 0x800812C4: the pin set-up for power-off (pull-ups, pin functions, port
    control registers);
  - 0x80038A9A: the panel's power-down (deep standby), per panel kind;
  - 0x80038018(0): the panel's cold power-on (reset pulse, power pin, the
    register set-up), per panel kind, up to and including command 0x38
    (the brightness part that follows depends on the OS's settings and is
    the display driver's business; DISPON is left to the driver, which
    repaints first; the level written by 0x51 is replaced by 0).
The OS version is checked by the SHA-256 of the routines' bytes.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sh4trace

PINS_OFF = 0x800812C4
LCD_OFF = 0x80038A9A
LCD_ON = 0x80038018
DELAYS = (0x80070020, 0x80038B64)
STUBS = {0x80039FB6: 0, 0x80039C34: 0}
CODE_RANGES = ((0x80081198, 0x800812D8), (0x80037500, 0x80038C60))
CODE_SHA256 = None      # filled in below after the first run on OS 02.01.7003

NEW_ID, OLD_ID = 0x16, 0x30

PADR, PHDR = 0xA4050120, 0xA405012E


def code_hash(rom):
    h = hashlib.sha256()
    for lo, hi in CODE_RANGES:
        h.update(rom[lo - 0x80000000:hi - 0x80000000])
    return h.hexdigest()


def pins_off(rom):
    e0 = sh4trace.trace(rom, PINS_OFF, fill=0)
    e1 = sh4trace.trace(rom, PINS_OFF, fill=1)
    ops = [e for e in sh4trace.merge_rmw(e0, e1) if e[0] == 'op']
    assert len(ops) == 26, len(ops)
    return [(a, size, andv, orv) for _, a, size, andv, orv in ops]


def lcd_stream(events, stop_after=None, on=False):
    """LCD traffic as 16-bit codes: 0x01cc command, 0x00dd parameter,
    0x2nnn delay of nnn ms, 0x4000 reset low, 0x4001 panel power on,
    0x4002 reset high."""
    out = []
    started = not on
    skip_delay = False
    i = 0
    while i < len(events):
        e = events[i]
        i += 1
        if e[0] == 'lcd' and e[1] == 'cmd':
            started = True
            c = e[2] & 0xFF
            if c == 0xDA:
                continue
            if on and c == 0x29:                # DISPON: the driver's, after its repaint
                skip_delay = True
                continue
            out.append(0x0100 | c)
            if on and c == 0x51:                # the level: 0 until the driver puts its own back
                assert events[i][0] == 'lcd' and events[i][1] == 'data'
                out.append(0x0000)
                i += 1
            if stop_after is not None and c == stop_after:
                break
        elif e[0] == 'lcd' and e[1] == 'data':
            out.append(e[2] & 0xFF)
        elif e[0] == 'delay':
            if skip_delay:
                skip_delay = False
                continue
            if started:
                out.append(0x2000 | (e[1] & 0xFFF))
        elif e[0] == 'w' and started and on:
            a, size, v = e[1], e[2], e[3]
            if a == PADR:
                out.append(0x4002 if v & 0x10 else 0x4000)
            elif a == PHDR:
                assert v & 0x20
                out.append(0x4001)
            else:
                raise SystemExit('unexpected write %08X in the LCD power-on' % a)
    return out


def lcd_off(rom, lcd_id):
    ev = sh4trace.trace(rom, LCD_OFF, fill=0, lcd_id=lcd_id, delays=DELAYS)
    s = lcd_stream(ev)
    # the driver has already sent the first part (backlight 0, DISPOFF, SLPIN): keep what follows SLPIN's delay
    k = s.index(0x0110)
    assert s[k + 1] & 0x2000
    return s[k + 2:]


def lcd_on(rom, lcd_id):
    ev = sh4trace.trace(rom, LCD_ON, args=(0,), fill=0, lcd_id=lcd_id, delays=DELAYS, stubs=STUBS, max_steps=3000000)
    return lcd_stream(ev, stop_after=0x38, on=True)


def c_array(name, ctype, values, fmt, per_line):
    lines = ['static const %s %s[] = {' % (ctype, name)]
    for i in range(0, len(values), per_line):
        lines.append('    ' + ' '.join(fmt % v + ',' for v in values[i:i + per_line]))
    lines.append('};')
    return '\n'.join(lines)


def generate(rom):
    h = code_hash(rom)
    pins = pins_off(rom)
    seqs = {
        'g_lcdOffNew': lcd_off(rom, NEW_ID), 'g_lcdOffOld': lcd_off(rom, OLD_ID),
        'g_lcdOnNew': lcd_on(rom, NEW_ID), 'g_lcdOnOld': lcd_on(rom, OLD_ID),
    }
    out = []
    out.append('''//------------------------------------------------------------------------------
//  classpad_pwrseq.h - what Casio's OS does to the hardware around power-off
//
//  GENERATED by tools/casio_poweroff_tables.py from a NOR dump (OS
//  02.01.7003, routines SHA-256 %s):
//  do not edit. The routines were run in tools/sh4trace.py and their
//  hardware accesses recorded.
//
//  g_pinsOff: 0x800812C4, the pin set-up for power-off: address, size in
//  bytes, AND mask, OR value (new = (old & AND) | OR; AND 0 = a plain write).
//  g_lcdOff*: the rest of the panel's power-down 0x80038A9A after SLPIN and
//  its delay (the display driver has sent backlight 0, DISPOFF, SLPIN).
//  g_lcdOn*: the panel's cold power-on 0x80038018(0) up to command 0x38,
//  without DISPON (the driver sends it after repainting) and with the
//  level of 0x51 at 0.
//  "New" is the panel answering ID 0x16 or 0x52, "Old" every other.
//  LCD stream codes: 0x01cc command cc, 0x00dd parameter dd, 0x2nnn wait
//  nnn ms, 0x4000 reset low (PADR bit 4), 0x4001 panel power on (PHDR bit
//  5), 0x4002 reset high.
//------------------------------------------------------------------------------
#ifndef __CLASSPAD_PWRSEQ_H
#define __CLASSPAD_PWRSEQ_H

typedef struct { UINT32 addr; UINT8 size; UINT32 andMask; UINT32 orValue; } CLASSPAD_PIN_OP;

#define LCDSEQ_CMD      0x0100
#define LCDSEQ_DELAY    0x2000
#define LCDSEQ_RESET_LO 0x4000
#define LCDSEQ_POWER_ON 0x4001
#define LCDSEQ_RESET_HI 0x4002
''' % h)
    out.append('static const CLASSPAD_PIN_OP g_pinsOff[] = {')
    for a, size, andv, orv in pins:
        out.append('    { 0x%08X, %d, 0x%0*X, 0x%0*X },' % (a, size, size * 2, andv, size * 2, orv))
    out.append('};\n')
    for name in ('g_lcdOffNew', 'g_lcdOffOld', 'g_lcdOnNew', 'g_lcdOnOld'):
        out.append(c_array(name, 'UINT16', seqs[name], '0x%04X', 12))
        out.append('')
    out.append('#endif')
    return '\n'.join(out) + '\n', h, pins, seqs


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    rom = open(argv[1], 'rb').read()
    out = 'bsp/classpad50/SRC/INC/classpad_pwrseq.h'
    if '-o' in argv:
        out = argv[argv.index('-o') + 1]
    text, h, pins, seqs = generate(rom)
    open(out, 'w', newline='').write(text.replace('\n', '\r\n'))
    print('routines SHA-256', h)
    print('%d pin operations; LCD off new %d, old %d codes; LCD on new %d, old %d codes -> %s' % (
        len(pins), len(seqs['g_lcdOffNew']), len(seqs['g_lcdOffOld']), len(seqs['g_lcdOnNew']), len(seqs['g_lcdOnOld']), out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
